// Builds src/features/keyboard/wordlist.js, the ranked English word list used
// for word suggestions.
//
// Source: FrequencyWords by Hermit Dave (OpenSubtitles 2018, English, 50k
// list), content licensed CC BY-SA 4.0:
//   https://github.com/hermitdave/FrequencyWords (content/2018/en/en_50k.txt)
// Offensive words are removed using the LDNOOBW list (CC BY 4.0):
//   https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
// Subtitle text is conversational, which suits spoken communication.
//
// Usage: node scripts/build-wordlist.mjs <en_50k.txt> <badwords.txt> [count]

import { readFileSync, writeFileSync } from "node:fs";

const [source, badSource, countArg] = process.argv.slice(2);
if (!source || !badSource) {
  console.error("Usage: node scripts/build-wordlist.mjs <en_50k.txt> <badwords.txt> [count]");
  process.exit(1);
}
const count = Number(countArg) || 15000;
const bad = new Set(readFileSync(badSource, "utf8").split(/\r?\n/).map((w) => w.trim().toLowerCase()).filter(Boolean));
// The source splits contractions ("don't" -> "don" + "t"); drop the halves.
// The predictor adds the full contractions itself.
const FRAGMENTS = new Set(["don", "didn", "doesn", "isn", "wasn", "weren", "aren", "couldn", "wouldn", "shouldn", "haven", "hasn", "hadn", "mustn", "needn", "ain", "ll", "ve", "re"]);
const words = [];
const seen = new Set();
for (const line of readFileSync(source, "utf8").split(/\r?\n/)) {
  const word = line.split(" ")[0]?.toLowerCase();
  if (!word || seen.has(word)) continue;
  if (!/^[a-z]+(?:'[a-z]+)?$/.test(word)) continue;
  if (word.length === 1 && word !== "a" && word !== "i") continue;
  if (FRAGMENTS.has(word)) continue;
  if (bad.has(word) || bad.has(word.replace(/'.*$/, "")) || bad.has(word.replace(/s$/, ""))) continue;
  seen.add(word);
  words.push(word);
  if (words.length >= count) break;
}
const header = `// Generated by scripts/build-wordlist.mjs. Do not edit by hand.
// ${words.length} English words, most frequent first.
// Data: FrequencyWords (c) Hermit Dave, CC BY-SA 4.0,
// https://github.com/hermitdave/FrequencyWords (OpenSubtitles 2018 English).
// Offensive words removed with the LDNOOBW list (CC BY 4.0).
`;
writeFileSync(new URL("../src/features/keyboard/wordlist.js", import.meta.url), `${header}export default ${JSON.stringify(words.join(" "))};\n`);
console.log(`Wrote ${words.length} words.`);
